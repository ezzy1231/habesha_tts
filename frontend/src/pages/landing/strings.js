export const PRICING = {
  platformFeePercent: 10,
  basePrice: 20,
  stepChars: 30,
  incrementPrice: 10,
  maxChars: 600,
};
export const KEEP_PERCENT = 100 - PRICING.platformFeePercent;

/** Same rule as priceForMessage() on the server: Ethiopic and emoji count as one character. */
export function priceForMessage(text) {
  const length = Array.from(String(text ?? '')).length;
  const steps = Math.max(1, Math.ceil(length / PRICING.stepChars));
  return PRICING.basePrice + (steps - 1) * PRICING.incrementPrice;
}

